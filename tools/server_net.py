#!/usr/bin/env python3
"""The Linux VMs' network: render each one's boot script and push it (lab.sh configure <node>).

/etc/local.d/evpn-3tier-net.start (OpenRC `local` service, so it runs at every boot) builds, from scratch each time:
  bond0      802.3ad (LACP, fast, layer3+4) over eth1 + eth2, the links to the VM's leaf pair (servers) or the border
             pair (load balancers); on the switches the two legs are one EVPN Ethernet Segment
  bond0.V    the VM's tier VLAN, its address .<hostnum>, default route via the anycast gateway .1; the OOB network
             keeps only 10.0.0.0/8 (management), so all tier traffic goes through the fabric

  server_net.py render <node>       print the script
  server_net.py push <node> [...]   install and run it over SSH (lab / lab, doas)"""
import json, subprocess, sys
from pathlib import Path
import paramiko

LAB = Path(__file__).resolve().parents[1]
SCRIPT = "/etc/local.d/evpn-3tier-net.start"


def inventory():
    return json.loads(subprocess.run([str(LAB / "lab.sh"), "inventory"], capture_output=True, text=True, check=True).stdout)


def render(inv, name):
    n = next(x for x in inv["nodes"] if x["name"] == name); net = n["net"]
    links = [p["name"] for p in n["ports"] if p.get("kind") == "access"]
    vif = f"bond0.{net['vlan']}"
    return "\n".join([
        "#!/bin/sh", f"# {name} ({n['role']}): generated by tools/server_net.py from lab.conf — rebuilt from scratch at every boot", "set -u",
        "modprobe bonding 2>/dev/null; modprobe 8021q 2>/dev/null",
        "ip link del bond0 2>/dev/null",
        *[f"ip link set {l} down; ip link set {l} nomaster 2>/dev/null" for l in links],
        "ip link add bond0 type bond mode 802.3ad lacp_rate fast miimon 100 xmit_hash_policy layer3+4",
        *[f"ip link set {l} master bond0" for l in links], "ip link set bond0 up",
        *[f"ip link set {l} up" for l in links],
        f"# VLAN {net['vlan']} (L2VNI {net['vni']}, VRF {net['vrf']}): {net['address']}, gateway {net['gateway']}",
        f"ip link add link bond0 name {vif} type vlan id {net['vlan']}",
        f"ip addr add {net['address']} dev {vif}", f"ip link set {vif} up",
        f"ip route replace default via {net['gateway']} dev {vif}",
    ]) + "\n"


def push(inv, name):
    n = next(x for x in inv["nodes"] if x["name"] == name); script = render(inv, name)
    c = paramiko.SSHClient(); c.set_missing_host_key_policy(paramiko.AutoAddPolicy())
    c.connect(n["mgmt_ip"], username="lab", password="lab", look_for_keys=False, allow_agent=False, timeout=20)
    try:
        i, o, e = c.exec_command(f"doas tee {SCRIPT} >/dev/null && doas chmod 755 {SCRIPT}"
                                 f" && doas rc-update add local default >/dev/null 2>&1; doas sh {SCRIPT} 2>&1; echo rc=$?", timeout=60)
        i.write(script); i.channel.shutdown_write()
        out = o.read().decode() + e.read().decode()
    finally:
        c.close()
    ok = out.strip().endswith("rc=0")
    print(f"[{name}] {'network applied' if ok else 'FAILED'}: {len(script.splitlines())} lines" + ("" if ok else f"\n{out[-600:]}"))
    return ok


if __name__ == "__main__":
    if len(sys.argv) < 3 or sys.argv[1] not in ("render", "push"): sys.exit(__doc__)
    inv = inventory()
    if sys.argv[1] == "render": print(render(inv, sys.argv[2]), end="")
    else: sys.exit(0 if all([push(inv, s) for s in sys.argv[2:]]) else 1)
